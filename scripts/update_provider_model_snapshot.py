"""Regenerate studio/backend/core/inference/provider_model_snapshot.py from models.dev."""

from __future__ import annotations

import json
import sys
import urllib.request
from datetime import date
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1] / "studio" / "backend"
OUTPUT = BACKEND / "core" / "inference" / "provider_model_snapshot.py"

sys.path.insert(0, str(BACKEND))
from core.inference.provider_model_capabilities import (  # noqa: E402
    MODELS_DEV_URL,
    models_dev_chat_models,
)


def main() -> int:
    request = urllib.request.Request(MODELS_DEV_URL, headers = {"User-Agent": "unsloth-studio"})
    with urllib.request.urlopen(request, timeout = 60) as response:
        catalog = models_dev_chat_models(json.load(response))
    lines = [
        "# SPDX-License-Identifier: AGPL-3.0-only",
        "# Copyright 2026-present the Unsloth AI Inc. team. All rights reserved. See /studio/LICENSE.AGPL-3.0",
        "",
        f"# Generated by scripts/update_provider_model_snapshot.py from {MODELS_DEV_URL} on {date.today().isoformat()}. Do not edit by hand.",
        "",
        "PROVIDER_MODEL_SNAPSHOT: dict[str, list[str]] = {",
    ]
    for provider_type, models in catalog.items():
        lines.append(f"    {json.dumps(provider_type)}: [")
        lines.extend(f"        {json.dumps(model_id)}," for model_id in models)
        lines.append("    ],")
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding = "utf-8")
    total = sum(len(models) for models in catalog.values())
    print(f"wrote {OUTPUT}: {total} models across {len(catalog)} providers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
