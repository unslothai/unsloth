#!/usr/bin/env node

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateCoverageRecords } from "./coverage-release-validator.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const MATRIX_PATH = resolve(ROOT, "docs/rag-platform/endpoint-coverage-matrix.json");
const INVENTORY_PATH = resolve(ROOT, "docs/rag-platform/route-inventory.json");
const OUTPUT = resolve(ROOT, "docs/rag-platform/backend-coverage-report.md");
const check = process.argv.includes("--check");
const matrix = JSON.parse(readFileSync(MATRIX_PATH, "utf8"));
const inventory = JSON.parse(readFileSync(INVENTORY_PATH, "utf8"));
const records = matrix.records;

const failures = validateCoverageRecords(records);

const count = (predicate) => records.filter(predicate).length;
const classes = [
  "frontend-screen",
  "frontend-action",
  "api-only",
  "external-callback",
  "internal",
  "unsupported",
];
const activePublic = count(
  (record) => record.runtime === "enabled" && record.class !== "internal",
);
const lines = [
  "# Rag Platform backend coverage report",
  "",
  "> Generated by `scripts/rag-platform/backend-coverage-report.mjs`. Do not edit by hand.",
  "",
  "## Release summary",
  "",
  "| Metric | Count |",
  "| --- | ---: |",
  `| Top-level routes | ${inventory.totals.routes} |`,
  `| Coverage records (including alternates) | ${records.length} |`,
  `| Active public records | ${activePublic} |`,
  ...classes.map((classification) =>
    `| ${classification} | ${count((record) => record.class === classification)} |`,
  ),
  `| Runtime-disabled | ${count((record) => record.runtime === "disabled")} |`,
  `| Not proxied | ${count((record) => record.runtime === "not-proxied")} |`,
  `| Planned / in-progress / unclassified | ${count((record) => ["planned", "in-progress", "unclassified"].includes(record.status))} |`,
  `| Reachable unsupported | ${count((record) => record.runtime === "enabled" && record.class === "unsupported")} |`,
  "",
  "## Runtime and proxy evidence",
  "",
  `- Python/MCP base source: \`${inventory.backend.source_ref}@${inventory.backend.source_commit}\`.`,
  `- Owned Go source: \`${inventory.backend.go_source_ref}@${inventory.backend.go_source_commit}\` (dirty: \`${inventory.backend.go_source_dirty}\`).`,
  `- Current Python audit source: \`${inventory.backend.forward_source_commit}\`.`,
  `- Proxy: \`${inventory.proxy.scheme}\`; Python API/admin 9380/9381 and Go API/admin 9384/9383.`,
  "- Runtime-disabled detail: `docs/rag-platform/runtime-disabled.md`.",
  "- Baseline diff: `docs/rag-platform/route-inventory-phase15-diff.json`.",
  "- Typed service/UI/contract evidence: `docs/rag-platform/endpoint-coverage-matrix.md`.",
  "- Mandatory E2E evidence: `docs/rag-platform/phase-15-e2e-evidence.json`.",
  "",
  "## Gate result",
  "",
  failures.length === 0
    ? "**PASS** — missing, duplicate, unclassified, reachable-unsupported and evidence-deficient record counts are zero."
    : `**FAIL** — ${failures.length} coverage violation(s).`,
  "",
];
const expected = `${lines.join("\n")}\n`;

if (check) {
  if (!existsSync(OUTPUT) || readFileSync(OUTPUT, "utf8") !== expected) {
    failures.push("backend coverage report is stale");
  }
} else {
  writeFileSync(OUTPUT, expected);
}

if (failures.length > 0) {
  for (const failure of failures) console.error(`coverage gate: ${failure}`);
  process.exit(1);
}
console.log(`backend coverage report PASS (${records.length} records)`);
