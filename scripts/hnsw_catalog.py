"""Writes studio/hnsw_prebuilt.txt, the hash-pinned requirements for the usearch + numkong pair, from
PyPI's metadata; --check exits 1 when the committed file differs."""

from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from pathlib import Path

PAIR = (("usearch", "2.26.6"), ("numkong", "7.8.6"))
PYTHONS = ("cp311", "cp312", "cp313", "cp314")
OUT = Path(__file__).resolve().parents[1] / "studio" / "hnsw_prebuilt.txt"
HEADER = """\
# Generated by scripts/hnsw_catalog.py. Every cp311 to cp314 wheel of the pair (no free-threaded builds):
# install_hnsw_prebuilt.py installs with --require-hashes --only-binary :all:, so only these exact files
# are ever installed and nothing is built from source.
"""


def _hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout = 30) as resp:
        files = json.load(resp)["urls"]
    out = []
    for f in files:
        if not f["filename"].endswith(".whl"):
            continue
        py, abi = f["filename"][:-4].split("-")[-3:-1]
        if py in PYTHONS and not abi.endswith("t"):
            out.append(f["digests"]["sha256"])
    return sorted(out)


def build() -> str:
    blocks = []
    for name, version in PAIR:
        lines = [f"{name}=={version}"] + [f"    --hash=sha256:{h}" for h in _hashes(name, version)]
        blocks.append(" \\\n".join(lines))
    return HEADER + "\n".join(blocks) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description = __doc__)
    ap.add_argument("--check", action = "store_true")
    args = ap.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding = "utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT} is stale: run scripts/hnsw_catalog.py", file = sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding = "utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
