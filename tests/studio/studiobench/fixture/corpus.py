"""The deterministic, frozen benchmark corpus.

THREE properties, and each of them was a bug in an earlier fixture:

1. **Frozen.** The text is generated once from a seed and written to `corpus/frozen/units.jsonl`,
   which SHIPS. A benchmark whose content is regenerated by whatever version of the generator the
   tester happens to have is not a benchmark, it is two different measurements with one name. The
   generator stays in the tree so the corpus can be rebuilt deliberately, and `manifest.json`
   carries a sha256 per unit so a rebuild that changes a single character is refused rather than
   quietly measured.

2. **Every unit unique.** Shiki caches highlighted output keyed on the SOURCE STRING. A fixture
   that repeats one fence pays the highlight cost exactly once and reports the other 99 as free,
   which is how a harness measures a 300K-character thread and finds no highlighting cost in it.
   Every fence here carries its unit index in its identifiers, so no two fences in the whole corpus
   are byte-identical and the cache never hits. Unique units are only half of it: a PLAN that hands
   one unit to more than one turn restores the caching without changing a byte of the corpus, which
   is what an index clamp in `plan_rung` used to do at the top rung. `check_streamed_units_are_new`
   states that half, and the manifest is sized from the ladder so no rung can reach it.

3. **The field's own span density.** The captured 90,262-character reply carried 16,186 highlight
   spans, i.e. 5.6 characters per span, which only happens if the content is nearly all fenced
   code. 1,250 characters of prose against an 1,800-character fence lands on that; an all-fence
   fixture measures 3.47, half again as much work per character as real content. Plus a fence-free
   PREAMBLE: the capture held a flat 60 fps and exactly zero spans for its first 33,348 characters
   and started dropping frames at the first CLOSED fence, so a fixture with no such stretch cannot
   show where the onset is, only that there is one.

The escalating cycle -- reasoning@10K, code@8K, reasoning@20K, code@16K, ... -- exists because a
thread of identical turns is not what gets slow. Each cycle doubles until the cap, so a long thread
is a few enormous replies among many small ones, which is the shape of a real session.
"""

