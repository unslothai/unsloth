def _queue(budget, slots, prompts, cap, charged, *, pausable = True):
    """Reserve ``prompts`` in order on a fresh queue; return (charges, which were granted)."""

    async def run():
        backend = _backend(budget, slots)
        reservations = []
        for prompt in prompts:
            reservation, _config = inf._openai_llama_admission_reserve(
                request = None,
                llama_backend = backend,
                payload = _chat(cap),
                counted_prompt_tokens = prompt,
                pausable = pausable,
            )
            reservations.append(reservation)
        granted = "".join("1" if r.lease_nowait() is not None else "0" for r in reservations)
        for reservation in reservations:
            reservation.cancel()
        return tuple(charged[-len(prompts) :]), granted

    return asyncio.run(run())


