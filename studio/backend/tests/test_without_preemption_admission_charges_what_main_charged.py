def _cap(kind, budget):
    return {
        "unstated": None,
        "256": 256,
        "below_window": budget - 1,
        "window": budget,
        "above_window": 2 * budget,
    }[kind]


class _Payload:
    def __init__(self, **fields):
        self.__dict__.update(fields)

    def __getattr__(self, _name):
        return None


def _chat(cap):
    return _Payload(messages = [{"role": "user", "content": "hi"}], max_tokens = cap)


_backend_ids = iter(range(1_000_000))


def _backend(budget, slots):
    return SimpleNamespace(
        base_url = f"http://main-parity-{next(_backend_ids)}",
        effective_parallel_slots = slots,
        _kv_cache_context_total = budget,
        context_length = budget,
        _kv_cache_unified = True,
        is_vision = False,
    )


