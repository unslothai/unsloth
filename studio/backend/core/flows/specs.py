def inp(
    id: str,
    type: str,
    label: Optional[str] = None,
    *,
    optional: bool = False,
    multi: bool = False,
    item: Optional[str] = None,
) -> dict:
    d: dict[str, Any] = {
        "id": id,
        "type": type,
        "label": label or id.replace("_", " ").title(),
        "optional": optional,
    }
    if multi:
        d["multi"] = True
    if item:
        d["item"] = item
    return d


def out(
    id: str,
    type: str,
    label: Optional[str] = None,
    *,
    item: Optional[str] = None,
) -> dict:
    d: dict[str, Any] = {"id": id, "type": type, "label": label or id.replace("_", " ").title()}
    if item:
        d["item"] = item
    return d


def P(
    id: str,
    kind: str,
    default: Any = None,
    label: Optional[str] = None,
    **extra: Any,
) -> dict:
    d: dict[str, Any] = {
        "id": id,
        "kind": kind,
        "default": default,
        "label": label or id.replace("_", " ").capitalize(),
    }
    d.update(extra)
    return d


def spec(
    type: str,
    title: str,
    category: str,
    description: str,
    *,
    inputs: list[dict] = (),
    outputs: list[dict] = (),
    params: list[dict] = (),
    lane: str = "cpu",
    model_kind: Optional[str] = None,
    cacheable: bool = True,
    side_effect: bool = False,
    icon: Optional[str] = None,
    v: int = 1,
    player: bool = False,
    entrypoint: bool = False,
    flow_in: bool = False,
    flow_out: Optional[list[str]] = None,
) -> dict:
    return {
        "type": type,
        "v": v,
        "title": title,
        "category": category,
        "description": description,
        "inputs": list(inputs),
        "outputs": list(outputs),
        "params": list(params),
        "lane": lane,  # cpu | gpu | player
        "model_kind": model_kind,
        "cacheable": cacheable and not side_effect,
        "side_effect": side_effect,
        "icon": icon,
        # player: authored for a player (story/world); the engine compiles it, never runs it as a step.
        "player": player,
        # entrypoint: can be invoked by name from a player (`/invoke`).
        "entrypoint": entrypoint,
        # flow_in/flow_out: story control handles (edges of kind "flow"). flow_out names the outgoing handles.
        "flow_in": flow_in,
        "flow_out": flow_out or [],
    }


