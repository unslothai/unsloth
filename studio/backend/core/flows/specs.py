def inp(
    id: str,
    type: str,
    label: Optional[str] = None,
    *,
    optional: bool = False,
    multi: bool = False,
    item: Optional[str] = None,
) -> dict:
    d: dict[str, Any] = {
        "id": id,
        "type": type,
        "label": label or id.replace("_", " ").title(),
        "optional": optional,
    }
    if multi:
        d["multi"] = True
    if item:
        d["item"] = item
    return d


def out(
    id: str,
    type: str,
    label: Optional[str] = None,
    *,
    item: Optional[str] = None,
) -> dict:
    d: dict[str, Any] = {"id": id, "type": type, "label": label or id.replace("_", " ").title()}
    if item:
        d["item"] = item
    return d


def P(
    id: str,
    kind: str,
    default: Any = None,
    label: Optional[str] = None,
    **extra: Any,
) -> dict:
    d: dict[str, Any] = {
        "id": id,
        "kind": kind,
        "default": default,
        "label": label or id.replace("_", " ").capitalize(),
    }
    d.update(extra)
    return d


