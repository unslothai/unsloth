def spec(
    type: str,
    title: str,
    category: str,
    description: str,
    *,
    inputs: list[dict] = (),
    outputs: list[dict] = (),
    params: list[dict] = (),
    lane: str = "cpu",
    model_kind: Optional[str] = None,
    cacheable: bool = True,
    side_effect: bool = False,
    icon: Optional[str] = None,
    v: int = 1,
    player: bool = False,
    entrypoint: bool = False,
    flow_in: bool = False,
    flow_out: Optional[list[str]] = None,
    requires: Optional[list[str]] = None,
    exclusive_gpu: bool = False,
    requires_approval: Optional[list[str]] = None,
) -> dict:
    inputs = list(inputs)
    for p in params:
        if p.get("bindable"):
            inputs.append(
                {
                    **inp(
                        f"param:{p['id']}",
                        BIND_TYPES.get(p["kind"], "any"),
                        p["label"],
                        optional = True,
                    ),
                    "param": p["id"],
                }
            )
    found = {
        "type": type,
        "v": v,
        "title": title,
        "category": category,
        "description": description,
        "inputs": inputs,
        "outputs": list(outputs),
        "params": list(params),
        "lane": lane,
        "model_kind": model_kind,
        "cacheable": cacheable and not side_effect,
        "side_effect": side_effect,
        "icon": icon,
        "player": player,
        "entrypoint": entrypoint,
        "flow_in": flow_in,
        "flow_out": flow_out or [],
    }
    if requires:
        found["requires"] = list(requires)
    if exclusive_gpu:
        # exclusive_gpu: hold the Studio-wide GPU lease while the node runs; such a node always runs on the GPU lane.
        found["exclusive_gpu"] = True
        found["lane"] = "gpu"
    if requires_approval:
        # requires_approval: python | http | mcp | provider | trigger, owner-approved per flow (core/flows/capabilities.py).
        found["requires_approval"] = list(requires_approval)
    return found


