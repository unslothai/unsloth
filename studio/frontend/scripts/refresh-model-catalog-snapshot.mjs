// Regenerates src/features/chat/model-catalog-snapshot.ts from https://models.dev/api.json.
// Usage: npm run catalog:refresh

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://models.dev/api.json";
const OUTPUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/features/chat/model-catalog-snapshot.ts",
);

const PROVIDER_MAP = {
  openai: "openai",
  anthropic: "anthropic",
  openrouter: "openrouter",
  google: "gemini",
  mistral: "mistral",
  deepseek: "deepseek",
  moonshotai: "kimi",
  cohere: "cohere",
  huggingface: "huggingface",
  alibaba: "qwen",
  "ollama-cloud": "ollama",
  lmstudio: "lmstudio",
};

const EFFORT_SCALE = ["none", "minimal", "low", "medium", "high", "xhigh", "max"];

function trimModel(model) {
  const entry = {};
  if (model.reasoning === true) entry.reasoning = true;
  const options = Array.isArray(model.reasoning_options) ? model.reasoning_options : [];
  const efforts = options.find((option) => option?.type === "effort")?.values;
  if (Array.isArray(efforts)) {
    const known = efforts.filter((level) => EFFORT_SCALE.includes(level));
    if (known.length > 0) {
      entry.efforts = [...known].sort(
        (a, b) => EFFORT_SCALE.indexOf(a) - EFFORT_SCALE.indexOf(b),
      );
    }
  }
  if (options.some((option) => option?.type === "toggle")) entry.toggle = true;
  const input = model.modalities?.input;
  if (Array.isArray(input) && input.length > 0) entry.input = input;
  // Total context window. limit.input is the prompt share, limit.output the completion cap.
  const context = model.limit?.context;
  if (typeof context === "number" && context > 0) entry.context = context;
  return entry;
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`${SOURCE_URL} responded ${response.status}`);
}
const catalog = await response.json();

const snapshot = {};
for (const [source, providerType] of Object.entries(PROVIDER_MAP)) {
  const models = catalog[source]?.models;
  if (!models || typeof models !== "object") continue;
  const bucket = snapshot[providerType] ?? {};
  for (const [modelId, model] of Object.entries(models)) {
    bucket[modelId.trim().toLowerCase()] = trimModel(model);
  }
  snapshot[providerType] = Object.fromEntries(
    Object.entries(bucket).sort(([a], [b]) => a.localeCompare(b)),
  );
}

const lines = [
  "// SPDX-License-Identifier: AGPL-3.0-only",
  "// Copyright 2026-present the Unsloth AI Inc. team. All rights reserved. See /studio/LICENSE.AGPL-3.0",
  "",
  `// Generated by scripts/refresh-model-catalog-snapshot.mjs from ${SOURCE_URL} on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
  "",
  "export interface ModelCatalogSnapshotEntry {",
  "  reasoning?: true;",
  "  efforts?: readonly string[];",
  "  toggle?: true;",
  "  input?: readonly string[];",
  "  /** Published context window in tokens. */",
  "  context?: number;",
  "}",
  "",
  "export const MODEL_CATALOG_SNAPSHOT: Readonly<",
  "  Record<string, Readonly<Record<string, ModelCatalogSnapshotEntry>>>",
  "> = {",
];
for (const [providerType, models] of Object.entries(snapshot)) {
  lines.push(`  ${JSON.stringify(providerType)}: {`);
  for (const [modelId, entry] of Object.entries(models)) {
    lines.push(`    ${JSON.stringify(modelId)}: ${JSON.stringify(entry)},`);
  }
  lines.push("  },");
}
lines.push("};", "");

writeFileSync(OUTPUT, lines.join("\n"));
const total = Object.values(snapshot).reduce((n, models) => n + Object.keys(models).length, 0);
console.log(`wrote ${OUTPUT}: ${total} models across ${Object.keys(snapshot).length} providers`);
