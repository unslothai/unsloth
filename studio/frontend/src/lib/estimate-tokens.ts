/** Roughly four characters per token, for budgets and previews where no tokenizer is at hand; undefined for blank text. */
export function estimateTokenCount(text: string): number | undefined {
  const trimmed = text.trim();
  if (!trimmed) {
    return undefined;
  }
  return Math.max(1, Math.round(trimmed.length / 4));
}
