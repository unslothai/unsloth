# Max blocks per chunk, keeps intermediates bounded for very large tensors.
_CHUNK_ELEMS = 1 << 24


def dequantize_gguf(
    packed: torch.Tensor,
    ggml_type: int,
    shape,
    dtype = torch.float32,
) -> torch.Tensor:
    ggml_type = int(ggml_type)
    fn = _DEQUANT.get(ggml_type)
    if fn is None:
        supported = ", ".join(GGML_TYPE_NAMES[t] for t in _DEQUANT)
        raise ValueError(f"Unsupported ggml type {_type_label(ggml_type)}; supported: {supported}")
    shape = tuple(int(s) for s in shape)
    if len(shape) == 0:
        raise ValueError("shape must have at least one dimension")
    n_rows = math.prod(shape[:-1])
    nbytes = n_rows * row_bytes(ggml_type, shape[-1])
    if packed.dtype != torch.uint8:
        packed = packed.contiguous().view(torch.uint8)
    if packed.numel() != nbytes:
        raise ValueError(
            f"{_type_label(ggml_type)} shape {shape} needs {nbytes} bytes, got {packed.numel()}"
        )
    block, size = GGML_BLOCK[ggml_type]
    blocks = packed.reshape(-1, size)
    n_blocks = blocks.shape[0]
    chunk = max(1, _CHUNK_ELEMS // block)
    if n_blocks <= chunk:
        return fn(blocks).reshape(shape).to(dtype)
    out = torch.empty((n_blocks, block), dtype = dtype, device = packed.device)
    for start in range(0, n_blocks, chunk):
        out[start : start + chunk] = fn(blocks[start : start + chunk]).to(dtype)
    return out.reshape(shape)
