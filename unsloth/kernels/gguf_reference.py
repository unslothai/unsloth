# E2M1 values doubled (kvalues_mxfp4).
_E2M1_KVALUES = (0, 1, 2, 3, 4, 6, 8, 12, 0, -1, -2, -3, -4, -6, -8, -12)
_IQ4NL_KVALUES = (-127, -104, -83, -65, -49, -35, -22, -10, 1, 13, 25, 38, 53, 69, 89, 113)
_IQ1_DELTA = 0.125


def _decode_grid(hex_bytes, grid_map, width):
    bits = math.ceil(math.log2(len(grid_map)))
    step = 8 // (8 // bits)
    mask = (1 << bits) - 1
    values = []
    for byte in bytes.fromhex(hex_bytes.decode("ascii")):
        for shift in range(0, 8, step):
            values.append(float(grid_map[(byte >> shift) & mask]))
    return torch.tensor(values, dtype = torch.float32).reshape(-1, width)


def _e4m3_values():
    # Signed E4M3 (fn): no inf, 0x7F / 0xFF are NaN.
    out = []
    for x in range(256):
        mag, exp, man = x & 0x7F, (x >> 3) & 0xF, x & 0x7
        if mag == 0x7F:
            out.append(float("nan"))
            continue
        v = math.ldexp(man, -9) if exp == 0 else math.ldexp(1.0 + man / 8.0, exp - 7)
        out.append(-v if x & 0x80 else v)
    return out


def _ue4m3_half_values():
    # NVFP4 block scale: unsigned E4M3, bit 7 ignored, 0x00 / 0x7F read as 0, times 0.5.
    out = []
    for x in range(256):
        exp, man = (x >> 3) & 0xF, x & 0x7
        v = math.ldexp(man, -9) if exp == 0 else math.ldexp(1.0 + man / 8.0, exp - 7)
        out.append(0.0 if x in (0, 0x7F) else v * 0.5)
    return out


def _ksigns_values():
    # Byte i of ggml ksigns_iq2xs: low 7 bits = i, bit 7 = parity of i.
    return [i | ((bin(i).count("1") & 1) << 7) for i in range(128)]


_TABLE_BUILDERS = {
    "e2m1": lambda: torch.tensor(_E2M1_KVALUES, dtype = torch.float32),
    "iq4nl": lambda: torch.tensor(_IQ4NL_KVALUES, dtype = torch.float32),
    "e4m3": lambda: torch.tensor(_e4m3_values(), dtype = torch.float32),
    "ue4m3_half": lambda: torch.tensor(_ue4m3_half_values(), dtype = torch.float32),
    "ksigns": lambda: torch.tensor(_ksigns_values(), dtype = torch.uint8),
}
for _name, _spec in _GRID_SPECS.items():
    _TABLE_BUILDERS[_name] = lambda _spec = _spec: _decode_grid(*_spec)

_TABLES = {}


def _table(name, device):
    key = (name, device)
    table = _TABLES.get(key)
    if table is None:
        cpu = _TABLES.get((name, torch.device("cpu")))
        if cpu is None:
            cpu = _TABLE_BUILDERS[name]()
            _TABLES[(name, torch.device("cpu"))] = cpu
        table = cpu.to(device)
        _TABLES[key] = table
    return table


# ---------------------------------------------------------------------------
# Byte helpers. Blocks are (n_blocks, bytes_per_block) uint8; GGUF is little endian.
# ---------------------------------------------------------------------------


def _f16(b):
    return b.contiguous().view(torch.float16).to(torch.float32)


def _u16(b):
    return b.contiguous().view(torch.int16).to(torch.int32) & 0xFFFF


def _u32(b):
    return b.contiguous().view(torch.int32).to(torch.int64) & 0xFFFFFFFF


def _shifts(x, shifts, mask, dim):
    # Stack (x >> s) & mask for each shift along a new axis `dim`.
    return torch.stack([(x >> s) & mask for s in shifts], dim = dim)


def _nibbles(x, dim):
    return _shifts(x, (0, 4), 0x0F, dim)


def _bits8(x):
    return _shifts(x, range(8), 1, -1)


def _sign_from_bits(bits):
    return torch.where(bits == 0, 1.0, -1.0).to(torch.float32)


# ---------------------------------------------------------------------------
# Per-type dequantizers: (n_blocks, bytes) uint8 -> (n_blocks, block) float32.
# ---------------------------------------------------------------------------


def _deq_f32(b):
    return b.contiguous().view(torch.float32).clone()


def _deq_f16(b):
    return _f16(b)


def _deq_bf16(b):
    return (b.contiguous().view(torch.int16).to(torch.int32) << 16).view(torch.float32)


def _deq_q4_0(b):
    n = b.shape[0]
    d = _f16(b[:, :2])
    q = _nibbles(b[:, 2:], 1).reshape(n, 32).to(torch.int32) - 8
    return d * q.to(torch.float32)


def _deq_q4_1(b):
    n = b.shape[0]
    d, m = _f16(b[:, :2]), _f16(b[:, 2:4])
    q = _nibbles(b[:, 4:], 1).reshape(n, 32).to(torch.float32)
    return (d * q) + m


def _q5_quants(qh_bytes, qs):
    n = qs.shape[0]
    shifts = torch.arange(32, device = qs.device, dtype = torch.int64)
    qh = (_u32(qh_bytes) >> shifts) & 1
    ql = _nibbles(qs, 1).reshape(n, 32).to(torch.int64)
    return ql | (qh << 4)


def _deq_q5_0(b):
    d = _f16(b[:, :2])
    q = _q5_quants(b[:, 2:6], b[:, 6:]) - 16
    return d * q.to(torch.float32)


def _deq_q5_1(b):
    d, m = _f16(b[:, :2]), _f16(b[:, 2:4])
    q = _q5_quants(b[:, 4:8], b[:, 8:]).to(torch.float32)
    return (d * q) + m


def _deq_q8_0(b):
    d = _f16(b[:, :2])
    x = b[:, 2:].contiguous().view(torch.int8).to(torch.float32)
    return x * d


def _deq_q2_k(b):
    n = b.shape[0]
    scales, qs = b[:, :16], b[:, 16:80]
    d, dmin = _f16(b[:, 80:82]), _f16(b[:, 82:84])
    dl = (d * (scales & 0xF).to(torch.float32)).reshape(n, 16, 1)
    ml = (dmin * (scales >> 4).to(torch.float32)).reshape(n, 16, 1)
    q = _shifts(qs.reshape(n, 2, 32), (0, 2, 4, 6), 3, 2).reshape(n, 16, 16)
    return (dl * q.to(torch.float32) - ml).reshape(n, QK_K)


def _deq_q3_k(b):
    n = b.shape[0]
    hmask, qs, scales = b[:, :32], b[:, 32:96], b[:, 96:108]
    d = _f16(b[:, 108:110])
    # 16 6-bit scales: low nibbles in bytes 0..7, high 2 bits in bytes 8..11.
    lo = _nibbles(scales[:, :8], 1).reshape(n, 16)
    hi = _shifts(scales[:, 8:], (0, 2, 4, 6), 3, 1).reshape(n, 16)
    sc = (lo | (hi << 4)).to(torch.int32) - 32
    dl = (d * sc.to(torch.float32)).reshape(n, 16, 1)
    ql = _shifts(qs.reshape(n, 2, 32), (0, 2, 4, 6), 3, 2).reshape(n, 16, 16)
    qh = _shifts(hmask.reshape(n, 1, 32), range(8), 1, 2).reshape(n, 16, 16) ^ 1
    q = ql.to(torch.int32) - (qh.to(torch.int32) << 2)
    return (dl * q.to(torch.float32)).reshape(n, QK_K)


def _k_scale_min(scales):
    # 8 6-bit scales and mins packed in 12 bytes (get_scale_min_k4).
    s = scales.reshape(-1, 3, 4)
    d, m, md = s[:, 0], s[:, 1], s[:, 2]
    sc = torch.cat([d & 0x3F, (md & 0x0F) | ((d >> 2) & 0x30)], dim = -1)
    mn = torch.cat([m & 0x3F, (md >> 4) | ((m >> 2) & 0x30)], dim = -1)
    return sc, mn


def _k_scaled(b):
    n = b.shape[0]
    d, dmin = _f16(b[:, :2]), _f16(b[:, 2:4])
    sc, mn = _k_scale_min(b[:, 4:16])
    dl = (d * sc.to(torch.float32)).reshape(n, 8, 1)
    dm = (dmin * mn.to(torch.float32)).reshape(n, 8, 1)
    return dl, dm


def _deq_q4_k(b):
    n = b.shape[0]
    dl, dm = _k_scaled(b)
    q = _nibbles(b[:, 16:].reshape(n, 4, 32), 2).reshape(n, 8, 32)
    return (dl * q.to(torch.float32) - dm).reshape(n, QK_K)


def _deq_q5_k(b):
    n = b.shape[0]
    dl, dm = _k_scaled(b)
    qh = _shifts(b[:, 16:48].reshape(n, 1, 32), range(8), 1, 2).reshape(n, 8, 32)
    ql = _nibbles(b[:, 48:].reshape(n, 4, 32), 2).reshape(n, 8, 32)
    q = (ql | (qh << 4)).to(torch.float32)
    return (dl * q - dm).reshape(n, QK_K)


def _deq_q6_k(b):
    n = b.shape[0]
    ql, qh = b[:, :128], b[:, 128:192]
    scales = b[:, 192:208].contiguous().view(torch.int8).to(torch.float32)
    d = (_f16(b[:, 208:210]) * scales).reshape(n, 16, 1)
    ql = _nibbles(ql.reshape(n, 2, 64), 2).reshape(n, 8, 32)
    qh = _shifts(qh.reshape(n, 2, 32), (0, 2, 4, 6), 3, 2).reshape(n, 8, 32)
    q = (ql | (qh << 4)).to(torch.int32) - 32
    return (d * q.reshape(n, 16, 16).to(torch.float32)).reshape(n, QK_K)


def _deq_tq1_0(b):
    n = b.shape[0]
    qs, qh = b[:, :48].to(torch.int32), b[:, 48:52].to(torch.int32)
    d = _f16(b[:, 52:54])
    # Base-3 digits: multiplying by 3^k (mod 256) moves digit k to the top.
    pow5 = torch.tensor([1, 3, 9, 27, 81], dtype = torch.int32, device = b.device).reshape(1, 5, 1)
    q0 = (qs[:, :32].reshape(n, 1, 32) * pow5).reshape(n, -1)
    q1 = (qs[:, 32:].reshape(n, 1, 16) * pow5).reshape(n, -1)
    q2 = (qh.reshape(n, 1, 4) * pow5[:, :4]).reshape(n, -1)
    q = torch.cat([q0, q1, q2], dim = -1) & 0xFF
    q = ((q * 3) >> 8) - 1
    return d * q.to(torch.float32)


def _deq_tq2_0(b):
    n = b.shape[0]
    d = _f16(b[:, 64:66])
    q = _shifts(b[:, :64].reshape(n, 2, 32), (0, 2, 4, 6), 3, 2).reshape(n, QK_K)
    return d * (q.to(torch.int32) - 1).to(torch.float32)


def _deq_q1_0(b):
    n = b.shape[0]
    d = _f16(b[:, :2])
    bits = _bits8(b[:, 2:]).reshape(n, 128)
    return torch.where(bits != 0, d, -d)


def _deq_q2_0(b):
    n = b.shape[0]
    d = _f16(b[:, :2])
    q = _shifts(b[:, 2:], (0, 2, 4, 6), 3, -1).reshape(n, 64)
    return d * (q.to(torch.int32) - 1).to(torch.float32)


