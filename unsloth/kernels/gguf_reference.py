def _type_label(ggml_type):
    name = GGML_TYPE_NAMES.get(ggml_type, _OTHER_NAMES.get(ggml_type, "unknown"))
    return f"{name} (id {ggml_type})"


def is_supported(ggml_type: int) -> bool:
    return int(ggml_type) in _DEQUANT


def row_bytes(ggml_type: int, cols: int) -> int:
    ggml_type = int(ggml_type)
    if ggml_type not in GGML_BLOCK:
        raise ValueError(f"Unsupported ggml type {_type_label(ggml_type)}")
    block, size = GGML_BLOCK[ggml_type]
    if cols % block != 0:
        raise ValueError(
            f"ggml type {_type_label(ggml_type)} needs cols to be a multiple of {block}, got {cols}"
        )
    return (cols // block) * size


