# Memoised on the class object, which is module level and outlives the process.
_ACCEPTED_CACHE = {}


def _accepted_parameters(config_class):
    """Names `config_class.__init__` accepts, and whether it takes `**kwargs`.

    A config with its own `**kwargs` may forward anywhere, so it is reported as
    accepting everything and the caller forwards unfiltered.
    """
    try:
        cached = _ACCEPTED_CACHE.get(config_class)
    except TypeError:  # unhashable, so uncacheable; fall through and recompute
        cached = None
    if cached is not None:
        return cached

    names = set()
    takes_var_keyword = False
    try:
        parameters = inspect.signature(config_class.__init__).parameters
    except (TypeError, ValueError):
        parameters = None

    if parameters is not None:
        for name, parameter in parameters.items():
            if name == "self":
                continue
            if parameter.kind is inspect.Parameter.VAR_KEYWORD:
                takes_var_keyword = True
            elif parameter.kind is not inspect.Parameter.VAR_POSITIONAL:
                names.add(name)
    elif dataclasses.is_dataclass(config_class):
        # Unreadable `__init__`: the field list is the next best description.
        names = {f.name for f in dataclasses.fields(config_class) if f.init}
    else:
        # Nothing to go on. Forward everything rather than guess.
        takes_var_keyword = True

    result = (frozenset(names), takes_var_keyword)
    try:
        _ACCEPTED_CACHE[config_class] = result
    except TypeError:  # unhashable class, vanishingly rare but not fatal
        pass
    return result


_MISSING = object()


def _field_default(config_class, name):
    """The declared default for `name`, or `_MISSING` if it cannot be read."""
    try:
        if dataclasses.is_dataclass(config_class):
            for field in dataclasses.fields(config_class):
                if field.name != name:
                    continue
                if field.default is not dataclasses.MISSING:
                    return field.default
                if field.default_factory is not dataclasses.MISSING:
                    return field.default_factory()
                return _MISSING
        parameter = inspect.signature(config_class.__init__).parameters.get(name)
        if parameter is not None and parameter.default is not inspect.Parameter.empty:
            return parameter.default
    except Exception:
        pass
    return _MISSING


def _is_untouched(config_class, name, value):
    """True if `value` is indistinguishable from `name`'s declared default."""
    default = _field_default(config_class, name)
    if default is _MISSING:
        return False
    try:
        return bool(default == value)
    except Exception:
        return default is value


def _default_notifier(message):
    print(message)


def rename_source(key):
    """Which project renamed `key`, so the message can name the right one.

    A user told "TRL renamed `warmup_ratio`" would go looking in the wrong
    changelog.
    """
    return "transformers" if key in TRANSFORMERS_CONFIG_RENAMES else "TRL"


def removal_source(key):
    """Which project retired `key`. Same reason as `rename_source`."""
    return "transformers" if key in TRANSFORMERS_REMOVED_FIELD_ADVICE else "TRL"


def classify_config_kwarg(config_class, key):
    """Say what `config_class` makes of `key`, without acting on it.

    Returns `(verdict, detail)`, one of:

        ("accepted", key)      the config declares this name
        ("rename", new_name)   TRL renamed the field and the new name is here
        ("retired", advice)    TRL removed the field; `advice` is the way out
        ("unknown", None)      not a name TRL ever had, so a caller mistake
        ("opaque", None)       the config declares nothing readable to judge by

    `filter_config_init_kwargs` below acts on the same verdicts, but it drops
    everything it does not recognise, which is right for a config constructor and
    wrong for a trainer kwarg: `unsloth/trainer.py` has to leave an unrecognised
    name on the trainer call so Python reports it. Exposing the verdict
    separately lets both callers share one policy and one table.

    A trailing `**kwargs` on the config is deliberately not treated as
    acceptance. The generated `Unsloth<X>Config.__init__` has one, and taking it
    at face value would classify every retired field as fine and put it back to
    being swallowed. Only a name the config actually declares counts.
    """
    accepted, takes_var_keyword = _accepted_parameters(config_class)
    if key in accepted:
        return "accepted", key
    if takes_var_keyword and not accepted:
        return "opaque", None

    # trl first: a name can be retired by trl while transformers still has it,
    # and the trl entry is the one that describes this config.
    for renames in (TRL_CONFIG_RENAMES, TRANSFORMERS_CONFIG_RENAMES):
        renamed = renames.get(key)
        if renamed is not None and renamed in accepted:
            return "rename", renamed

    for table in (TRL_REMOVED_FIELD_ADVICE, TRANSFORMERS_REMOVED_FIELD_ADVICE):
        advice = table.get(key)
        if advice is not None:
            return "retired", advice

    return "unknown", None


def filter_config_init_kwargs(
    config_class,
    kwargs,
    notify = None,
):
    """Return `kwargs` reduced to what `config_class.__init__` will accept.

    Renames are applied where TRL or transformers documented one; everything else
    the config rejects is dropped. Each decision is reported through `notify`
    (`print` by default, which shows up reliably in a notebook).

    The per-name decision is `classify_config_kwarg` above, shared with the
    trainer-kwarg path in `unsloth/trainer.py`; the both-names-set arbitration
    below stays here because only this caller can see the whole kwargs dict.
    """
    if not kwargs:
        return kwargs

    accepted, takes_var_keyword = _accepted_parameters(config_class)
    if takes_var_keyword:
        return kwargs

    if notify is None:
        notify = _default_notifier
    config_name = getattr(config_class, "__name__", str(config_class))

    # Two passes so the outcome does not depend on dict ordering: take what the
    # config accepts, then rename or drop the leftovers.
    forwarded = {key: value for key, value in kwargs.items() if key in accepted}

    for key, value in kwargs.items():
        if key in accepted:
            continue

        verdict, detail = classify_config_kwarg(config_class, key)

        if verdict == "rename":
            renamed = detail
            # The new name is a mirrored parameter, so it is already in the dict
            # carrying either the caller's value or the class default. Only
            # overwrite the default: an explicitly set new name wins.
            existing = kwargs.get(renamed, _MISSING)
            who = rename_source(key)
            if existing is _MISSING or _is_untouched(config_class, renamed, existing):
                forwarded[renamed] = value
                notify(
                    f"Unsloth: {who} renamed `{key}` to `{renamed}`. Forwarding your "
                    f"value to `{renamed}` - update your code when convenient."
                )
            else:
                notify(
                    f"Unsloth: `{key}` was renamed to `{renamed}` by {who} and this "
                    f"{config_name} accepts only the new name. You set both, so "
                    f"`{key}` is ignored and your `{renamed}` is kept."
                )
            continue

        if verdict == "retired":
            notify(
                f"Unsloth: `{key}` is not supported by the installed "
                f"{removal_source(key)}'s {config_name} and will be IGNORED - {detail}."
            )
        else:
            notify(
                f"Unsloth: `{key}` is not a valid {config_name} argument for the "
                f"installed TRL and will be IGNORED. Check the spelling, or your "
                f"TRL version if this argument used to work."
            )

    return forwarded
