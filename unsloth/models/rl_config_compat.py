"""Forward only the config arguments the installed TRL still accepts.

The `Unsloth<X>Config.__init__` generated by `unsloth/models/rl.py` ends in a
`**kwargs` catch-all splatted into `super().__init__()`, so an argument TRL has
since retired crashes the base dataclass (`max_prompt_length` was removed from
`GRPOConfig` in 0.28.0, and fourteen `DPOConfig` fields in 0.29.0), breaking
pinned scripts that were correct when written. Stdlib only, so the generated
cache file can import it behind a try/except without pulling in torch.

Three outcomes per unrecognised argument: TRL documented a rename and the new
name exists, so the value is moved across; TRL removed the field, so it is
dropped and reported by name with TRL's advice; anything else is dropped with
a warning.

That last case means `GRPOConfig(learnign_rate = 3e-4)` now warns instead of
raising `TypeError`. The trade is accepted: a typo is still surfaced loudly,
whereas the crash it replaces hits correct code on a TRL upgrade and cannot be
fixed without editing library code.
"""

